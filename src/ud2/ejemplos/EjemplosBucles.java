package ud2.ejemplos;

public class EjemplosBucles {
    public static void main(String[] args) {

        // Bucle de cero repeticiones
        int contador = -8;
        while (contador >= 0) {
            // Cuerpo del bucle
            System.out.println(contador);
        }

        // Bucle infinito
        while (contador < 0) {
            // Cuerpo del bucle
            System.out.println(contador);
        }

        

    }
}
