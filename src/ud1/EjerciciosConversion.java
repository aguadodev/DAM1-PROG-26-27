package ud1;

public class EjerciciosConversion {
    public static void main(String[] args) {
        int a = 10;
        double b = a;
        System.out.println(b);

        double x = 9.99;
        int y = (int) x;
        System.out.println(y);

        short s = 5;
        int i = s;
        long l = i;
        float f = l;
        double d = f;
        System.out.println(d);

        int a2 = 5;
        int b2 = 2;
        double resultado = a2 / b2;
        System.out.println(resultado);

    }
}
